import { spawn } from "child_process";
import * as fs from "fs";
import * as path from "path";
import { Autostart, AutostartSpec } from "./Autostart";
import { CommandRunner } from "./CommandRunner";

// ---------------------------------------------------------------------------------
// Windows: a per-user Run registry value (no admin needed) that runs a tiny
// VBScript, which starts node with no console window.
// ---------------------------------------------------------------------------------
export class WindowsAutostart implements Autostart {
    static readonly RUN_KEY = "HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run";
    static readonly VALUE_NAME = "hompag";
    readonly description = "Windows Run key (HKCU\\...\\CurrentVersion\\Run\\hompag)";

    constructor(private runner = new CommandRunner()) {}

    static scriptPath(spec: AutostartSpec) { return path.join(spec.appHome, "hompag-autostart.vbs"); }

    static renderScript(spec: AutostartSpec) {
        const q = (s: string) => s.replace(/"/g, '""');
        return [
            "' Starts the hompag supervisor without a console window.",
            "' Generated by the hompag installer; re-run 'hompag install' to change it.",
            'Set shell = CreateObject("WScript.Shell")',
            `shell.Run """${q(spec.nodePath)}"" ""${q(spec.launcherPath)}"" run", 0, False`,
            "",
        ].join("\r\n");
    }

    static renderRunValue(spec: AutostartSpec) {
        return `wscript.exe "${WindowsAutostart.scriptPath(spec)}"`;
    }

    static writeScript(spec: AutostartSpec) {
        fs.mkdirSync(spec.appHome, { recursive: true });
        fs.writeFileSync(WindowsAutostart.scriptPath(spec), WindowsAutostart.renderScript(spec));
    }

    async register(spec: AutostartSpec) {
        WindowsAutostart.writeScript(spec);
        const result = await this.runner.run("reg", ["add", WindowsAutostart.RUN_KEY,
            "/v", WindowsAutostart.VALUE_NAME, "/t", "REG_SZ", "/d", WindowsAutostart.renderRunValue(spec), "/f"]);
        if (result.code !== 0) throw new Error(`Could not add the autostart registry value: ${result.stderr.trim()}`);
    }

    async unregister() {
        if (await this.isRegistered()) {
            await this.runner.run("reg", ["delete", WindowsAutostart.RUN_KEY, "/v", WindowsAutostart.VALUE_NAME, "/f"]);
        }
    }

    async isRegistered() {
        const result = await this.runner.run("reg", ["query", WindowsAutostart.RUN_KEY, "/v", WindowsAutostart.VALUE_NAME]);
        return result.code === 0;
    }

    // ---------------------------------------------------------------------------------
    // Start the supervisor through wscript even when autostart is off.  A process
    // node spawns directly inherits every inheritable handle node has, including a
    // caller's stdout pipe, which would then never close ("hompag start | more"
    // would hang).  WScript.Shell.Run doesn't pass handles on, and wscript exits
    // right away.
    // ---------------------------------------------------------------------------------
    async startNow(spec: AutostartSpec) {
        WindowsAutostart.writeScript(spec);
        const child = spawn("wscript.exe", [WindowsAutostart.scriptPath(spec)], { detached: true, stdio: "ignore", windowsHide: true });
        child.on("error", () => {});
        child.unref();
    }
}
